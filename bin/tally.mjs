#!/usr/bin/env node
/**
 * Keep a site's Tally forms as code. Settings are under `tally` in the repo's
 * casomo.config.mjs (see tally/config.mjs); the API key is read from the
 * environment variable they name.
 *
 *   tally push <form> [--discard-edits] [--delete-answers]
 *                                 push a form, read it back, report any
 *                                 difference
 *   tally diff <form>             editor edits not yet in the code, and code
 *                                 changes not yet pushed
 *   tally tokens [--check]        rewrite the form stylesheet's TOKENS block,
 *                                 or fail if it is out of date
 *
 * A form with no id in the registry is created as a draft and its id written
 * back; a form with one is replaced in place, keeping its uuids and so its
 * answers. A push is refused when it would delete answers the live form holds,
 * because Tally deletes them with the question, option or field, and when it
 * would delete edits made in Tally's editor since the last push. Each refusal
 * has its own flag to override it, so getting past one never switches off the
 * other. The editor's unpublished changes are invisible to the API: publish
 * there first.
 *
 * `push`, `diff` and `tokens --check` exit 1 on a difference, so a script can
 * gate on them.
 */
import {readFile, writeFile} from "node:fs/promises";
import {EDITOR, tallyClient} from "../tally/client.mjs";
import {
  baseline, CHANGE_KINDS, codeVersion, droppedAnswers, formChanges, liveVersion,
  pushedStore, pushRefusal, unportedEdits,
} from "../tally/compare.mjs";
import {formRegistry, loadForms, loadTallySettings} from "../tally/config.mjs";
import {toSettings, translate} from "../tally/translator.mjs";
import {findBlock, TOKENS_END, tokensBlock} from "../tokens/block.mjs";

/** @import {TallyForm} from "../tally/client.mjs" */
/** @import {TallySiteSettings} from "../tally/config.mjs" */

/** Push over edits made in Tally's editor since the last push. */
const DISCARD_EDITS = "--discard-edits";
/** Push a form that drops questions, options or fields holding answers. */
const DELETE_ANSWERS = "--delete-answers";
const CHECK = "--check";

const USAGE = `usage: tally push <form> [${DISCARD_EDITS}] [${DELETE_ANSWERS}]`
  + ` | diff <form> | tokens [${CHECK}]`;

/** The exit status for a command line that can't be run as written, apart
 *  from 1, which every command uses for a difference or a refusal. */
const EXIT_USAGE = 2;

/** The node binary and this script come before the command. */
const FIRST_ARG = 2;

/** The form stylesheet's generated block. */
const TOKENS = {
  start: "/* TOKENS: generated by `tally tokens` */",
  end: TOKENS_END,
  what: "the form stylesheet",
};

/**
 * Each command, the flags it takes, and whether it names a form. A map, so a
 * name that is only inherited from Object (`constructor`) names nothing.
 * @type {Map<string, {run: (settings: TallySiteSettings,
 *   form: string | undefined, flags: Set<string>) => Promise<void>,
 *   flags: string[], form: boolean}>}
 */
const COMMANDS = new Map([
  ["push", {run: push, flags: [DISCARD_EDITS, DELETE_ANSWERS], form: true}],
  ["diff", {run: diff, flags: [], form: true}],
  ["tokens", {run: tokens, flags: [CHECK], form: false}],
]);

const [name, ...args] = process.argv.slice(FIRST_ARG);
const command = name === undefined ? undefined : COMMANDS.get(name);
const flags = new Set(args.filter((a) => a.startsWith("--")));
const positional = args.filter((a) => !a.startsWith("--"));
const unknown = [...flags].filter((f) => !command?.flags.includes(f));
const wantForm = command?.form ? 1 : 0;
if (!command || unknown.length > 0 || positional.length !== wantForm) {
  if (unknown.length > 0) console.error(`tally: unknown flag ${unknown.join(", ")}`);
  console.error(USAGE);
  process.exit(EXIT_USAGE);
}
await command.run(await loadTallySettings(), positional[0], flags);

/**
 * What every form command starts from: the form named, what the code writes
 * for it with a name for each block, the store of last pushes, the registry
 * of ids and a client.
 * @param {TallySiteSettings} settings
 * @param {string | undefined} formKey
 */
async function formCommand(settings, formKey) {
  const forms = await loadForms(settings);
  const form = formKey === undefined ? undefined : forms.get(formKey);
  if (!form) {
    const known = [...forms.keys()].join(", ") || "none: check tally.forms";
    throw new Error(`no form ${formKey}; the forms are ${known}`);
  }
  const apiKey = process.env[settings.apiKeyEnv];
  if (!apiKey) throw new Error(`${settings.apiKeyEnv} is not set`);
  const {blocks, name: blockName} = translate(form);
  const settingsOut = toSettings(form);
  return {
    form,
    blocks,
    settingsOut,
    code: codeVersion(blocks, settingsOut),
    name: blockName,
    store: pushedStore(settings.pushed),
    registry: formRegistry(settings.registry),
    api: tallyClient(apiKey),
  };
}

/** @typedef {Awaited<ReturnType<typeof formCommand>>} FormCommand */

/**
 * Refuse a push that would delete answers or editor edits, each unless its
 * own flag says to.
 * @param {FormCommand} cmd
 * @param {TallyForm} live
 * @param {Set<string>} flags
 */
async function refuseUnsafe(cmd, live, flags) {
  const {version: pushed, recorded} = await baseline(cmd.store, cmd.form.key, cmd.code);
  const held = liveVersion(live, cmd.code, pushed);
  const refusal = pushRefusal({
    dropped: droppedAnswers(live, cmd.blocks),
    edits: unportedEdits(pushed, cmd.code, held, cmd.name).length,
    recorded,
  }, {
    deleteAnswers: flags.has(DELETE_ANSWERS),
    discardEdits: flags.has(DISCARD_EDITS),
  }, {deleteAnswers: DELETE_ANSWERS, discardEdits: DISCARD_EDITS});
  if (refusal) throw new Error(refusal);
}

/** Send the form: replace it in place, or create it and record its id.
 *  @param {FormCommand} cmd @param {string | undefined} existing */
async function send(cmd, existing) {
  if (existing) return cmd.api.replace(existing, cmd.blocks, cmd.settingsOut);
  const sent = await cmd.api.create(cmd.blocks, cmd.settingsOut);
  await cmd.registry.record(cmd.form.key, sent.id);
  return sent;
}

/** @param {TallySiteSettings} settings @param {string | undefined} formKey
 *  @param {Set<string>} flags */
async function push(settings, formKey, flags) {
  const cmd = await formCommand(settings, formKey);
  const existing = await cmd.registry.maybeIdOf(cmd.form.key);
  if (existing) await refuseUnsafe(cmd, await cmd.api.read(existing), flags);
  const sent = await send(cmd, existing);
  const held = await cmd.api.read(sent.id);
  // Tally adds blocks of its own around what it is sent; only what was sent
  // has to come back.
  const differences = formChanges(cmd.code, liveVersion(held, cmd.code), cmd.name)
    .filter((c) => c.kind !== CHANGE_KINDS.Added)
    .map((c) => c.line);
  await cmd.store.write(cmd.form.key, cmd.code);
  console.log(`${cmd.form.key} → ${EDITOR}/${sent.id} (${held.status})`);
  console.log(`${cmd.blocks.length} blocks sent, ${held.blocks.length} held`);
  if (differences.length > 0) {
    console.log(differences.join("\n"));
    process.exitCode = 1;
  }
}

/** @param {TallySiteSettings} settings @param {string | undefined} formKey */
async function diff(settings, formKey) {
  const cmd = await formCommand(settings, formKey);
  const {version: pushed, recorded} = await baseline(cmd.store, cmd.form.key, cmd.code);
  if (!recorded) {
    console.log("No record of the last push: comparing the live form with the code.");
  }
  const id = await cmd.registry.idOf(cmd.form.key);
  const live = liveVersion(await cmd.api.read(id), cmd.code, pushed);
  /** @param {{line: string}[]} changes */
  const lines = (changes) => changes.map((c) => c.line);
  const edits = lines(unportedEdits(pushed, cmd.code, live, cmd.name));
  const unpushed = lines(formChanges(pushed, cmd.code, cmd.name));
  console.log(`Edited in Tally and not yet in the code: ${edits.length}`);
  for (const line of edits) console.log(`  ${line}`);
  console.log(`Changed in the code, not yet pushed: ${unpushed.length}`);
  for (const line of unpushed) console.log(`  ${line}`);
  if (edits.length > 0) process.exitCode = 1;
}

/** @param {TallySiteSettings} settings @param {string | undefined} _form
 *  @param {Set<string>} flags */
async function tokens(settings, _form, flags) {
  if (settings.tokens.length === 0) {
    throw new Error("casomo.config.mjs names no tally.tokens to copy: the "
      + "TOKENS block would be emptied");
  }
  const css = await readFile(settings.globals, "utf8");
  const sheet = await readFile(settings.stylesheet, "utf8");
  const {s, e} = findBlock(sheet, TOKENS);
  const block = tokensBlock(css, settings.tokens, TOKENS);
  const next = sheet.slice(0, s) + block + sheet.slice(e);
  if (!flags.has(CHECK)) {
    await writeFile(settings.stylesheet, next);
    return;
  }
  if (next !== sheet) {
    console.error(`tally tokens: ${settings.stylesheet} is out of date with `
      + `${settings.globals}: run tally tokens, then push the forms.`);
    process.exitCode = 1;
  }
}
