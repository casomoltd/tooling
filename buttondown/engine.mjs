/** Whether `index` sits directly in a top-level `:root` or `@theme` block:
 *  `:root.dark`, `:root[data-theme]` and a `:root` nested in an at-rule are
 *  variants of the token, not the token. */
function isBaseBlock(css, index) {
  const depth = [...css.slice(0, index)].reduce(
    (d, c) => d + (c === "{") - (c === "}"), 0,
  );
  const head = enclosing(css, index);
  return depth === 1 && (head === ":root" || /^@theme(\s|$)/.test(head));
}

/** The head of the block enclosing `index`, or "" at the top level. A
 *  comment before the head is not part of it, even one holding a `;`. */
function enclosing(css, index) {
  let depth = 0;
  for (let i = index; i >= 0; i -= 1) {
    if (css[i] === "}") depth += 1;
    if (css[i] === "{") {
      if (depth === 0) {
        const head = css.slice(0, i);
        const tail = head.slice(Math.max(head.lastIndexOf("}"),
          head.lastIndexOf(";"), head.lastIndexOf("{")) + 1);
        return stripComments(tail).replace(/^[\s\S]*\*\//, "").trim();
      }
      depth -= 1;
    }
  }
  return "";
}

/** The one TOKENS block's bounds; anything else is refused, since a
 *  missing, repeated or reversed pair would slice the wrong text. */
function markers(web) {
  const s = web.indexOf(START);
  const e = web.indexOf(END);
  if (s === -1 || e === -1 || e < s
    || web.indexOf(START, s + 1) !== -1 || web.indexOf(END, e + 1) !== -1) {
    throw new Error("the web skin needs exactly one TOKENS block, start "
      + "before end");
  }
  return {s, e: e + END.length};
}

function longHex(hex) {
  const h = hex.slice(1).toLowerCase();
  return h.length <= 4 ? `#${[...h].map((c) => c + c).join("")}` : `#${h}`;
}

/** Each rule as [selector, body], selectors whitespace-normalised. A rule
 *  inside an at-rule takes the text after the at-rule's own brace. */
function rules(text) {
  return stripComments(text).split("}").flatMap((chunk) => {
    const brace = chunk.lastIndexOf("{");
    if (brace === -1) return [];
    const head = chunk.slice(0, brace);
    const selector = head.slice(head.lastIndexOf("{") + 1)
      .split(/\s+/).join(" ").trim();
    return [[selector, chunk.slice(brace + 1)]];
  });
}

/** Each declaration in a stylesheet as [property, value]. */
function declarations(text) {
  return rules(text).flatMap(([, body]) => body.split(";").flatMap((decl) => {
    const at = decl.indexOf(":");
    return at === -1
      ? []
      : [[decl.slice(0, at).trim(), decl.slice(at + 1).trim()]];
  }));
}

/** Declaration values only, so a selector such as `a:not(#cafe)` is not
 *  read as a colour. */
function cssValues(text) {
  return declarations(text).map(([, value]) => value).join(" ");
}

/** An SVG's attribute values. */
function attributeValues(text) {
  return [...text.matchAll(/="([^"]*)"/g)].map((m) => m[1]).join(" ");
}

function offPalette(values, palette) {
  return [...new Set(
    [...values.matchAll(/#[0-9a-f]{3,8}\b/gi)]
      .map((m) => m[0])
      .filter((hex) => !palette.has(longHex(hex))),
  )];
}

function hides(text) {
  return rules(text)
    .filter(([, body]) => body.split(";").some((decl) =>
      /^(display:none|font-size:0)(!important)?$/.test(
        decl.replace(/\s/g, ""),
      )))
    .map(([selector]) => selector);
}

function injections(text) {
  return rules(text)
    .filter(([selector, body]) => !selector.startsWith("@")
      && body.split(";").some((decl) => {
        // Anchored: justify-, align- and place-content end in content too.
        const m = decl.match(/^\s*content\s*:\s*(.*?)\s*(!important)?\s*$/);
        return m && !NO_CONTENT.has(m[1]);
      }))
    .map(([selector]) => selector);
}

/** Every href attribute selector the skin keys on that names no socials
 *  URL, quoted either way or unquoted. */
function orphanHrefs(text, urls) {
  const matches = {
    "=": (url, v) => url === v,
    "~=": (url, v) => url.split(/\s+/).includes(v),
    "|=": (url, v) => url === v || url.startsWith(`${v}-`),
    "*=": (url, v) => url.includes(v),
    "^=": (url, v) => url.startsWith(v),
    "$=": (url, v) => url.endsWith(v),
  };
  return [...stripComments(text).matchAll(
    /\[\s*href\s*([~|*^$]?=)\s*(?:"([^"]*)"|'([^']*)'|([^\s\]]+))(?:\s+[is])?\s*\]/gi,
  )]
    .filter(([, op, d, s, bare]) =>
      !urls.some((url) => matches[op](url, d ?? s ?? bare)))
    .map(([whole]) => whole);
}

/**
 * Each tag in tags.json whose live fields differ, keyed by id rather than
 * name: a tag's name is the label a subscriber reads in their preferences,
 * so renaming one is an ordinary edit, and a lookup by name would miss on
 * exactly that edit. The name is the fallback for a tag whose id is not
 * written in yet; a tag found by neither comes back without a `tagId`.
 */
async function tagDrift(settings, api) {
  const file = path.join(settings.dir, "tags.json");
  if (!existsSync(file)) return [];
  const live = await api.list("/tags");
  return JSON.parse(await readFile(file, "utf8")).flatMap(({id, ...body}) => {
    const current = live.find((t) => t.id === id)
      ?? (id ? undefined : live.find((t) => t.name === body.name));
    if (current && same("tag", current, body)) return [];
    return [{tagId: current?.id, body}];
  });
}
