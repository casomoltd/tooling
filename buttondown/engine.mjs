const API = "https://api.buttondown.com/v1";

/** The API's own path prefix, which every request path sits under. */
const API_PATH = new URL(API).pathname;

/** The status of an email not yet sent. */
const DRAFT = "draft";

const FRONT_MATTER = /^---\n([\s\S]*?)\n---\n/;

/** The Buttondown fields holding the two skins. */
const SKIN = {web: "web_css", email: "css"};

/** Fields Buttondown stores behind its image proxy. */
const IMAGE_FIELDS = new Set(["icon", "image"]);

/** The newsletter's identity, which only casomo.config.mjs may carry: a
 *  field of that name in newsletter.json would be sent as a setting. */
const IDENTITY = ["id", "publicId", "username"];

/** Hrefs Buttondown draws itself, which no socials entry names. */
const BUTTONDOWN_LINKS = ["buttondown.com"];

/** The shared web rules' opening line, which marks a composed skin, and
 *  the variables those rules read, which such a skin must declare. */
const BASE_WEB = readFileSync(new URL("./base-web.css", import.meta.url), "utf8");
const BASE_MARK = BASE_WEB.slice(0, BASE_WEB.indexOf("\n"));
const BASE_VARS = [...new Set(
  [...BASE_WEB.matchAll(/var\((--[\w-]+)/g)].map((m) => m[1]),
)];

/** Values of `content:` that remove text rather than inject it. */
const NO_CONTENT = new Set(["none", "normal", '""', "''"]);

/** Shorter fields are settings, not documents, and `emit` leaves them to
 *  newsletter.json, where they already read plainly. */
const EMIT_MIN_LENGTH = 200;

/** The repo's settings, every path absolute. Throws where the newsletter
 *  or the tokens file is not named, since either would otherwise be
 *  guessed. */
export async function loadSettings(root = process.cwd()) {
  const config = await loadCasomoConfig("buttondown", root);
  const {id, username} = config.newsletter ?? {};
  if (!id || !username) {
    throw new Error(
      "casomo.config.mjs needs buttondown.newsletter with an id and a "
      + "username: it is the one newsletter this repo may write to",
    );
  }
  if (!config.globals) {
    throw new Error("casomo.config.mjs needs buttondown.globals: the "
      + "stylesheet the site's design tokens are declared in");
  }
  const at = (p) => path.resolve(root, p);
  const dir = at(config.dir ?? "buttondown");
  return {
    root,
    newsletter: config.newsletter,
    dir,
    globals: at(config.globals),
    tokens: config.tokens ?? [],
    extra: config.extra ?? [],
    asserts: config.asserts ?? {},
    allowedHides: config.allowedHides ?? {},
    linkClasses: Object.values(config.linkClasses ?? {}),
    ownLinks: [...BUTTONDOWN_LINKS, ...(config.ownLinks ?? [])],
    // The file holding the web skin's TOKENS block, which `tokens`
    // rewrites: the field file itself unless the field is composed.
    webSkin: config.webSkin
      ? at(config.webSkin) : path.join(dir, "fields", "web_css.css"),
    paletteFiles: (config.paletteFiles ?? []).map(at),
    checks: (config.checks ?? []).map(at),
  };
}

/**
 * The value of one custom property, declared in a `:root` or `@theme`
 * block: a `.dark {}` or `@media` override elsewhere in the file is a
 * variant, not the token. Throws if absent, since a renamed token would
 * otherwise leave a stale copy behind.
 */
export function readToken(css, name) {
  const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  for (const m of css.matchAll(
    new RegExp(`^\\s*${escaped}:\\s*([^;]+);`, "gm"),
  )) {
    if (isBaseBlock(css, m.index)) {
      return m[1].trim();
    }
  }
  throw new Error(`${name} not found in a :root or @theme block`);
}

/** A reader for one stylesheet's tokens, for a repo's email blocks. */
export async function tokenReader(file) {
  const css = await readFile(file, "utf8");
  return (name) => readToken(css, name);
}

/** Every field the newsletter is set to: newsletter.json, then fields/. */
export async function buildPayload(settings) {
  const payload = await readNewsletter(settings);
  const identity = IDENTITY.filter((key) => key in payload);
  if (identity.length) {
    throw new Error(
      `newsletter.json holds ${identity.join(", ")}: the newsletter's `
      + "identity belongs in casomo.config.mjs, not among its fields",
    );
  }
  const dir = path.join(settings.dir, "fields");
  for (const file of (await readdir(dir)).sort()) {
    const field = file.replace(/\.[a-z]+$/, "");
    if (field in payload) {
      throw new Error(
        `${field} is set in both newsletter.json and fields/${file}`,
      );
    }
    const full = path.join(dir, file);
    if (!file.endsWith(".mjs")) {
      payload[field] = await readFile(full, "utf8");
      continue;
    }
    // A module may build a structured field too, such as `socials` from
    // the site's own footer links, so the two cannot drift apart.
    const value = (await import(pathToFileURL(full).href)).default;
    if (typeof value !== "string" && (!value || typeof value !== "object")) {
      throw new Error(`fields/${file} must default-export a string, an `
        + `array or an object, got ${value === null ? "null" : typeof value}`);
    }
    payload[field] = value;
  }
  return payload;
}

/** The generated block of the web skin, from the site's tokens. */
export function tokensBlock(settings, css) {
  return [
    START,
    ...settings.tokens.map(
      ([target, source]) =>
        `  ${target}: ${readToken(css, source)}; /* ${source} */`,
    ),
    // A value starting `--` is read from the tokens; any other is literal.
    ...settings.extra.map(
      ([target, value]) =>
        `  ${target}: ${
          value.startsWith("--") ? readToken(css, value) : value
        };`,
    ),
    END,
  ].join("\n");
}

/** Rewrites the web skin's TOKENS block from the site's tokens. */
export async function writeTokens(settings) {
  const css = await readFile(settings.globals, "utf8");
  const file = settings.webSkin;
  const web = await readFile(file, "utf8");
  const {s, e} = markers(web);
  await writeFile(
    file, web.slice(0, s) + tokensBlock(settings, css) + web.slice(e),
  );
}

/** Every problem with the repo's skins and settings; empty when clean. */
export async function runCheck(settings) {
  const css = await readFile(settings.globals, "utf8");
  const payload = await buildPayload(settings);
  // The skins as sent, base rules and site rules together, so what is
  // checked is what Buttondown receives. Absent, there is nothing to
  // check, which is refused rather than passed.
  for (const field of Object.values(SKIN)) {
    if (typeof payload[field] !== "string") {
      throw new Error(`the payload has no ${field} field to check`);
    }
  }
  const web = payload[SKIN.web];
  const email = payload[SKIN.email];
  const problems = [];

  // An @import must be a whole statement before any rule: a browser
  // ignores one after a rule, and one whose URL was cut short swallows
  // what follows it. Read past the leading statements as the composer
  // does; any @import left over, outside a string, is one of those.
  const rest = stripComments(web.slice(preludeEnd(web)))
    .replace(/"[^"]*"|'[^']*'/g, '""');
  if (/@import/i.test(rest)) {
    problems.push("the web skin has an @import that is not a complete "
      + "statement before its first rule, which a browser ignores");
  }

  // Every variable the shared rules read, and every --bd-* role read
  // anywhere, must be declared, or the declaration reading it is dropped
  // without an error.
  const plain = stripComments(web);
  const declared = new Set(
    [...plain.matchAll(/(--[\w-]+)\s*:/g)].map((m) => m[1]),
  );
  const read = new Set([
    ...web.includes(BASE_MARK) ? BASE_VARS : [],
    ...[...plain.matchAll(/var\((--bd-[\w-]+)/g)].map((m) => m[1]),
  ]);
  for (const name of read) {
    if (!declared.has(name)) {
      problems.push(`the web skin reads ${name}, which nothing declares: `
        + "map it in the TOKENS block");
    }
  }

  if (settings.tokens.length || settings.extra.length) {
    const {s, e} = markers(web);
    if (web.slice(s, e) !== tokensBlock(settings, css)) {
      problems.push("the TOKENS block is stale: run `buttondown tokens`");
    }
  }
  for (const [name, want] of Object.entries(settings.asserts)) {
    const got = readToken(css, name);
    if (got !== want) {
      problems.push(`${name} is ${got} in the site's tokens; the skins `
        + `depend on it being ${want}`);
    }
  }

  // The palette is every hex the tokens file declares. Only hex is
  // checked: an rgb() or named colour in a skin is not caught.
  const palette = new Set(
    [...css.matchAll(/#[0-9a-f]{3,8}\b/gi)].map((m) => longHex(m[0])),
  );
  const sources = [
    ["web skin", cssValues(web)],
    ["email skin", cssValues(email)],
    ...await Promise.all(settings.paletteFiles.map(async (file) => [
      path.relative(settings.root, file),
      attributeValues(await readFile(file, "utf8")),
    ])),
  ];
  for (const [where, values] of sources) {
    for (const hex of offPalette(values, palette)) {
      problems.push(`off-palette colour ${hex} in ${where}`);
    }
  }

  for (const [where, text] of [["web skin", web], ["email skin", email]]) {
    for (const selector of hides(text)) {
      if (!(selector in settings.allowedHides)) {
        problems.push(`${where} hides ${selector}, which allowedHides `
          + "does not list: restyle Buttondown's markup, don't hide it");
      }
    }
    for (const selector of injections(text)) {
      problems.push(`${where} injects text with content: in ${selector}`);
    }
  }

  const urls = [
    ...(payload.socials ?? []).map((s) => s.url),
    ...settings.ownLinks,
  ];
  for (const selector of orphanHrefs(web, urls)) {
    problems.push(`${selector} in the web skin matches no socials URL`);
  }

  const emailRules = stripComments(email);
  for (const name of settings.linkClasses) {
    if (!new RegExp(`a\\.${name}(?![\\w-])`).test(emailRules)) {
      problems.push(`email class "${name}" has no a.${name} rule, so `
        + "the template's link colour would override it");
    }
  }

  for (const file of settings.checks) {
    const check = (await import(pathToFileURL(file).href)).default;
    const found = await check({
      root: settings.root, payload, css, web, email, readToken,
    });
    if (!Array.isArray(found)) {
      throw new Error(`${path.relative(settings.root, file)} must resolve `
        + "to an array of problems");
    }
    problems.push(...found);
  }
  return problems;
}

/** The API key, from the file `BUTTONDOWN_KEY_FILE` names: a path can be
 *  passed around freely, while a key on a command line sits in the shell
 *  history and in `ps`. */
export async function readKey(env = process.env) {
  const file = env.BUTTONDOWN_KEY_FILE;
  if (!file) {
    throw new Error("set BUTTONDOWN_KEY_FILE to the file holding the key");
  }
  const key = (await readFile(file.replace(/^~(?=\/)/, os.homedir()),
    "utf8")).trim();
  if (!key) throw new Error(`${file} is empty`);
  return key;
}

/**
 * A client for the one newsletter. The key reaches every newsletter on the
 * account, so each request carries Buttondown-Context with this id, and
 * Buttondown refuses an unknown id rather than falling back to the
 * account's default newsletter.
 */
export function client(settings, key) {
  const {newsletter} = settings;
  async function call(method, url, body, {form} = {}) {
    const res = await fetch(new URL(API + url), {
      method,
      headers: {
        Authorization: `Token ${key}`,
        "Buttondown-Context": newsletter.id,
        ...(form ? {} : {"Content-Type": "application/json"}),
      },
      body: form ?? (body === undefined ? undefined : JSON.stringify(body)),
    });
    const text = await res.text();
    let data = null;
    try {
      data = text ? JSON.parse(text) : null;
    } catch {
      // Reported as the detail, so a non-JSON refusal still says why.
      data = {detail: text};
    }
    return {ok: res.ok, status: res.status, data};
  }

  /** Writing to the wrong newsletter must not happen, so the newsletter
   *  read before a write and the one a write returns are both checked.
   *  Buttondown names a newsletter by its UUID and, on some endpoints, a
   *  prefixed `publicId`; only those two are accepted. */
  function assertNewsletter(got, when) {
    const ids = [newsletter.id, newsletter.publicId].filter(Boolean);
    if (!ids.includes(got?.id) || got?.username !== newsletter.username) {
      throw new Error(`${when}: got ${got?.username} (${got?.id}), `
        + `expected ${newsletter.username} (${newsletter.id})`);
    }
  }

  async function live() {
    const res = await call("GET", newsletterPath(newsletter));
    if (!res.ok) throw new Error(`GET newsletter: ${detail(res)}`);
    assertNewsletter(res.data, "before writing");
    return res.data;
  }

  /** Every page of a list endpoint. A failed page throws: an empty list
   *  would read as "none on the account" and skip what is there. */
  async function list(url) {
    const items = [];
    for (let next = url; next;) {
      const res = await call("GET", next);
      if (!res.ok) throw new Error(`GET ${next}: ${detail(res)}`);
      items.push(...res.data.results);
      const more = res.data.next && new URL(res.data.next);
      next = more ? more.pathname.slice(API_PATH.length) + more.search : null;
    }
    return items;
  }

  return {call, assertNewsletter, live, list};
}

/**
 * Refuses an `api` call that writes newsletter settings anywhere but this
 * newsletter. Judged on the path the server routes: percent-decoded, then
 * normalised, so `/%6eewsletters/<other>`, `/./newsletters/<other>` and
 * `<own>/../<other>` are seen for what they are. A path still encoded after
 * one decoding is refused outright rather than guessed at.
 */
export function assertApiPath(settings, method, url) {
  if (method.toUpperCase() === "GET") return;
  const decoded = decodeURIComponent(new URL(API + url).pathname);
  if (decoded.includes("%")) {
    throw new Error(`api refuses an encoded path: ${url}`);
  }
  const {pathname} = new URL(decoded, API);
  const own = API_PATH + newsletterPath(settings.newsletter);
  if (pathname.startsWith(`${API_PATH}/newsletters`)
    && pathname !== own && !pathname.startsWith(`${own}/`)) {
    throw new Error(`api writes under /newsletters only to ${own}`);
  }
}

/** Whether a live value already says what the repo wants. */
export function same(field, got, want) {
  if (IMAGE_FIELDS.has(field)) {
    if (!want) return !got;
    let url;
    try {
      url = new URL(got);
    } catch {
      // Unset, or not a URL at all: not the image the repo names.
      return false;
    }
    // Buttondown stores an image behind its proxy, with the original URL
    // percent-encoded in the path, so compare the decoded host and path.
    const decoded = decodeURIComponent(`${url.origin}${url.pathname}`);
    const w = new URL(want);
    return decoded.endsWith(`${w.host}${w.pathname}`);
  }
  if (typeof want === "string") {
    return typeof got === "string" && got.trim() === want.trim();
  }
  if (Array.isArray(want)) {
    return Array.isArray(got) && got.length === want.length
      && want.every((item, i) => same(field, got[i], item));
  }
  if (want && typeof want === "object") {
    // A live object may carry keys the repo does not set.
    return !!got && typeof got === "object"
      && Object.entries(want).every(([k, v]) => same(k, got[k], v));
  }
  return got === want;
}

/** What live differs in: the newsletter's fields and its tags. */
export async function drift(settings, api) {
  const [payload, current, tags] = await Promise.all([
    buildPayload(settings), api.live(), tagDrift(settings, api),
  ]);
  return {
    payload,
    differs: Object.keys(payload).filter(
      (field) => !same(field, current[field], payload[field]),
    ),
    tags,
  };
}

/**
 * Patches what differs, in one call where Buttondown takes it. A
 * plan-gated field makes Buttondown refuse the whole call, naming a
 * feature rather than the field, so a refusal falls back to one field at
 * a time. Returns what was refused, so a caller can fail on a partial
 * write.
 */
export async function apply(settings, api, log = console.log) {
  const {payload, differs, tags} = await drift(settings, api);
  const refused = [];
  if (!differs.length && !tags.length) {
    log("buttondown: live already matches");
    return {refused};
  }
  if (differs.length) {
    const url = newsletterPath(settings.newsletter);
    const body = Object.fromEntries(differs.map((f) => [f, payload[f]]));
    const whole = await api.call("PATCH", url, body);
    if (whole.ok) {
      api.assertNewsletter(whole.data, "after writing");
      log(`buttondown: updated ${differs.join(", ")}`);
    } else {
      log(`buttondown: whole PATCH refused (${detail(whole)}); `
        + "field by field:");
      for (const field of differs) {
        const one = await api.call("PATCH", url, {[field]: payload[field]});
        if (one.ok) {
          api.assertNewsletter(one.data, "after writing");
          log(`  ok       ${field}`);
        } else {
          refused.push(field);
          log(`  REFUSED  ${field}: ${detail(one)}`);
        }
      }
    }
  }
  for (const {tagId, body} of tags) {
    if (!tagId) {
      refused.push(`tag ${body.name}`);
      log(`  tag ${body.name}: not on the account`);
      continue;
    }
    const res = await api.call("PATCH", `/tags/${tagId}`, body);
    if (!res.ok) refused.push(`tag ${body.name}`);
    log(`  tag ${body.name}: ${res.ok ? "updated" : `REFUSED ${detail(res)}`}`);
  }
  return {refused};
}

/**
 * A draft from a markdown file whose first line, after any front matter,
 * is `# Subject`. Front matter carries the email's id once it exists, so a
 * re-run replaces that draft rather than creating a second; `slug` and
 * `description` are passed through, and `image` (the share image) defaults
 * to the newsletter's own. An email already sent is refused:
 * replacing it would rewrite the published archive.
 */
export async function draft(settings, api, file, log = console.log) {
  const raw = await readFile(file, "utf8");
  const m = raw.match(FRONT_MATTER);
  const fm = Object.fromEntries((m?.[1] ?? "").split("\n")
    .filter((line) => line.includes(":"))
    .map((line) => {
      const at = line.indexOf(":");
      return [line.slice(0, at).trim(), line.slice(at + 1).trim()];
    }));
  const lines = (m ? raw.slice(m[0].length) : raw).trimStart().split("\n");
  if (!lines[0]?.startsWith("# ")) {
    throw new Error("after any front matter, the first line must be "
      + "`# Subject`");
  }
  if ("id" in fm && !fm.id) {
    throw new Error("front matter has an empty `id:`; delete the line to "
      + "create a draft");
  }
  if ("image" in fm && !fm.image) {
    throw new Error("front matter has an empty `image:`; delete the line "
      + "to use the newsletter's share image");
  }
  // The marker says the body is markdown (Buttondown's `plaintext` mode).
  // Without it Buttondown guesses, and a draft once stored as rich text
  // takes the next PATCH as rich text too.
  const body = {
    subject: lines[0].slice(2).trim(),
    body: "<!-- buttondown-editor-mode: plaintext -->\n"
      + lines.slice(1).join("\n").trim(),
    ...Object.fromEntries(["slug", "description"]
      .filter((k) => k in fm).map((k) => [k, fm[k]])),
  };
  // Left unset, Buttondown takes the post's first picture as its share
  // image, so every post would preview differently; the newsletter's own
  // share image is the default, and `image:` in the front matter wins.
  const image = "image" in fm
    ? fm.image : (await readNewsletter(settings)).image;
  if (image) {
    assertAbsoluteUrl("image", image);
    body.image = image;
  }
  if (fm.id) {
    const current = await api.call("GET", `/emails/${fm.id}`);
    if (!current.ok) throw new Error(`GET email: ${detail(current)}`);
    if (current.data.status !== DRAFT) {
      throw new Error(`${fm.id} is ${current.data.status}, not a draft; `
        + "replacing it would rewrite what was published");
    }
    const res = await api.call("PATCH", `/emails/${fm.id}`, body);
    if (!res.ok) throw new Error(`refused: ${detail(res)}`);
    log(`updated draft ${res.data.id}`);
    return;
  }
  const res = await api.call("POST", "/emails", {...body, status: DRAFT});
  if (!res.ok) throw new Error(`refused: ${detail(res)}`);
  const withId = m
    ? `---\nid: ${res.data.id}\n${raw.slice(4)}`
    : `---\nid: ${res.data.id}\n---\n${raw}`;
  await writeFile(file, withId);
  log(`created draft ${res.data.id}; id written back into ${file}`);
}

/** Uploads an image and returns its Buttondown URL: the newsletter's
 *  images must be Buttondown's own, not linked from elsewhere. */
export async function upload(api, file) {
  const form = new FormData();
  form.append("image", new Blob([await readFile(file)]), path.basename(file));
  const res = await api.call("POST", "/images", undefined, {form});
  if (!res.ok || !res.data?.image) {
    throw new Error(`upload refused: ${detail(res)}`);
  }
  return res.data.image;
}

/** Writes each long field out as rendered, so what Buttondown receives
 *  can be read and diffed directly. */
export async function emit(settings, dir) {
  const payload = await buildPayload(settings);
  await mkdir(dir, {recursive: true});
  const written = [];
  for (const [field, value] of Object.entries(payload)) {
    if (typeof value !== "string" || value.length < EMIT_MIN_LENGTH) continue;
    await writeFile(path.join(dir, field), value);
    written.push(field);
  }
  return written;
}

/**
 * Where a stylesheet's leading statements end: its opening comments and its
 * `@charset`, `@import` and `@layer` statements, which must come before any
 * rule. An @import's URL may hold semicolons (a font request's weights), so
 * it is read whole before its closing `;`; one that isn't a whole statement
 * ends the leading statements there.
 */
export function preludeEnd(css) {
  let at = 0;
  for (;;) {
    // A URL never holds a newline or a brace, so one that does is an
    // import cut short, and ends the leading statements there.
    const url = "(?:\"[^\"\\n{}]*\"|'[^'\\n{}]*')";
    const lead = css.slice(at).match(new RegExp(
      "^\\s*(\\/\\*[\\s\\S]*?\\*\\/|@charset\\s+\"[^\"]*\";"
      + `|@import\\s+(?:url\\((?:${url}|[^)"'\\n{}]*)\\)|${url})[^;{]*;`
      + "|@layer\\s+[^;{]*;)", "i",
    ));
    if (!lead) return at;
    at += lead[0].length;
  }
}

/** Comments removed by index rather than a lazy regex, which backtracks
 *  between its two literals. */
export function stripComments(text) {
  let out = "";
  let at = 0;
  for (;;) {
    const open = text.indexOf("/*", at);
    if (open === -1) return out + text.slice(at);
    out += text.slice(at, open);
    const close = text.indexOf("*/", open + 2);
    if (close === -1) return out;
    at = close + 2;
  }
}

/** Throws unless an image field holds an absolute URL, since Buttondown
 *  stores a relative one as given and the image then never loads. */
function assertAbsoluteUrl(field, value) {
  if (!URL.canParse(value)) {
    throw new Error(`${field} must be an absolute URL, got `
      + JSON.stringify(value));
  }
}

/** newsletter.json, parsed and with its image fields checked. */
async function readNewsletter(settings) {
  const file = path.join(settings.dir, "newsletter.json");
  let payload;
  try {
    payload = JSON.parse(await readFile(file, "utf8"));
  } catch (error) {
    throw new Error(`${file}: ${error.message}`, {cause: error});
  }
  for (const field of IMAGE_FIELDS) {
    if (payload[field]) assertAbsoluteUrl(field, payload[field]);
  }
  return payload;
}

/** Why a call failed: Buttondown's `detail`, else its whole body, which
 *  names the fields it refused, else the status. */
function detail(res) {
  return JSON.stringify(res.data?.detail ?? res.data ?? res.status);
}

