/**
 * The gate on a newsletter's skins and settings, behind `buttondown check`:
 * what Buttondown would receive, read against the site's design tokens and
 * the repo's own allowances. A problem is a string; none means clean.
 */
import {readFileSync} from "node:fs";
import {readFile} from "node:fs/promises";
import path from "node:path";
import {
  findBlock, readToken, stripComments, TOKENS_END,
  tokensBlock as tokenLines,
} from "../tokens/block.mjs";

export const START = "/* TOKENS: generated by `buttondown tokens` */";
export const END = TOKENS_END;

/** The Buttondown fields holding the two skins. */
const SKIN = {web: "web_css", email: "css"};

/** The shared web rules' opening line, which marks a composed skin, and
 *  the variables those rules read, which such a skin must declare. */
const BASE_WEB = readFileSync(new URL("./base-web.css", import.meta.url), "utf8");
const BASE_MARK = BASE_WEB.slice(0, BASE_WEB.indexOf("\n"));
const BASE_VARS = [...new Set(
  [...BASE_WEB.matchAll(/var\((--[\w-]+)/g)].map((m) => m[1]),
)];

/** Values of `content:` that remove text rather than inject it. */
const NO_CONTENT = new Set(["none", "normal", '""', "''"]);

/** The longest short-form hex, `#rgba`, without its `#`. */
const SHORT_HEX = 4;

/** The flag that marks a declaration important, which a `content:` value
 *  may end in. */
const IMPORTANT = "!important";

/** What may follow an href selector's value: an optional `i` or `s` flag.
 *  Checked apart from the selector's own pattern, which stays linear. */
const HREF_FLAG = /^(?:\s+[is])?\s*$/i;

/** The generated block of the web skin, from the site's tokens. */
export function tokensBlock(settings, css) {
  return tokenLines(css, settings.tokens, {start: START, end: END}, settings.extra);
}

/** The skins as sent, base rules and site rules together, so what is
 *  checked is what Buttondown receives. Absent, there is nothing to check,
 *  which is refused rather than passed. */
export function skinsOf(payload) {
  for (const field of Object.values(SKIN)) {
    if (typeof payload[field] !== "string") {
      throw new Error(`the payload has no ${field} field to check`);
    }
  }
  return {web: payload[SKIN.web], email: payload[SKIN.email]};
}

/** Every problem with the skins and settings in `payload`, read against
 *  the site's tokens `css`; empty when clean. */
export async function skinProblems(settings, {css, payload}) {
  const skins = skinsOf(payload);
  return [
    ...importProblems(skins.web),
    ...undeclaredProblems(skins.web),
    ...tokenProblems(settings, css, skins.web),
    ...await paletteProblems(settings, css, skins),
    ...hideProblems(settings, skins),
    ...hrefProblems(settings, payload, skins.web),
    ...linkClassProblems(settings, skins.email),
  ];
}

/**
 * Where a stylesheet's leading statements end: its opening comments and its
 * `@charset`, `@import` and `@layer` statements, which must come before any
 * rule. An @import's URL may hold semicolons (a font request's weights), so
 * it is read whole before its closing `;`; one that isn't a whole statement
 * ends the leading statements there.
 */
export function preludeEnd(css) {
  let at = 0;
  for (;;) {
    // A URL never holds a newline or a brace, so one that does is an
    // import cut short, and ends the leading statements there.
    const url = "(?:\"[^\"\\n{}]*\"|'[^'\\n{}]*')";
    const lead = css.slice(at).match(new RegExp(
      "^\\s*(\\/\\*[\\s\\S]*?\\*\\/|@charset\\s+\"[^\"]*\";"
      + `|@import\\s+(?:url\\((?:${url}|[^)"'\\n{}]*)\\)|${url})[^;{]*;`
      + "|@layer\\s+[^;{]*;)", "i",
    ));
    if (!lead) return at;
    at += lead[0].length;
  }
}

/** The one TOKENS block's bounds in the web skin. */
export function markers(web) {
  return findBlock(web, {start: START, end: END, what: "the web skin"});
}

/** An @import must be a whole statement before any rule: a browser ignores
 *  one after a rule, and one whose URL was cut short swallows what follows
 *  it. Read past the leading statements as the composer does; any @import
 *  left over, outside a string, is one of those. */
function importProblems(web) {
  const rest = stripComments(web.slice(preludeEnd(web)))
    .replace(/"[^"]*"|'[^']*'/g, '""');
  return /@import/i.test(rest)
    ? ["the web skin has an @import that is not a complete statement before "
      + "its first rule, which a browser ignores"]
    : [];
}

/** Every variable the shared rules read, and every --bd-* role read
 *  anywhere, must be declared, or the declaration reading it is dropped
 *  without an error. */
function undeclaredProblems(web) {
  const plain = stripComments(web);
  const declared = new Set(
    [...plain.matchAll(/--[\w-]+/g)]
      .filter((m) => followedByColon(plain, m.index + m[0].length))
      .map((m) => m[0]),
  );
  const read = new Set([
    ...web.includes(BASE_MARK) ? BASE_VARS : [],
    ...[...plain.matchAll(/var\((--bd-[\w-]+)/g)].map((m) => m[1]),
  ]);
  return [...read].filter((name) => !declared.has(name))
    .map((name) => `the web skin reads ${name}, which nothing declares: `
      + "map it in the TOKENS block");
}

/** Whether `text` has a colon at `at`, after any whitespace: a sticky
 *  match from one place, so no name is read twice. */
function followedByColon(text, at) {
  const colon = /\s*:/y;
  colon.lastIndex = at;
  return colon.test(text);
}

/** A stale TOKENS block, and any token the skins depend on that has moved. */
function tokenProblems(settings, css, web) {
  const problems = [];
  if (settings.tokens.length || settings.extra.length) {
    const {s, e} = markers(web);
    if (web.slice(s, e) !== tokensBlock(settings, css)) {
      problems.push("the TOKENS block is stale: run `buttondown tokens`");
    }
  }
  for (const [name, want] of Object.entries(settings.asserts)) {
    const got = readToken(css, name);
    if (got !== want) {
      problems.push(`${name} is ${got} in the site's tokens; the skins `
        + `depend on it being ${want}`);
    }
  }
  return problems;
}

/** The palette is every hex the tokens file declares. Only hex is checked:
 *  an rgb() or named colour in a skin is not caught. */
async function paletteProblems(settings, css, {web, email}) {
  const palette = new Set(
    [...css.matchAll(/#[0-9a-f]{3,8}\b/gi)].map((m) => longHex(m[0])),
  );
  const sources = [
    ["web skin", cssValues(web)],
    ["email skin", cssValues(email)],
    ...await Promise.all(settings.paletteFiles.map(async (file) => [
      path.relative(settings.root, file),
      attributeValues(await readFile(file, "utf8")),
    ])),
  ];
  return sources.flatMap(([where, values]) => offPalette(values, palette)
    .map((hex) => `off-palette colour ${hex} in ${where}`));
}

/** Each hide allowedHides does not list, and each text injection. */
function hideProblems(settings, {web, email}) {
  return [["web skin", web], ["email skin", email]].flatMap(([where, text]) => [
    ...hides(text).filter((selector) => !(selector in settings.allowedHides))
      .map((selector) => `${where} hides ${selector}, which allowedHides `
        + "does not list: restyle Buttondown's markup, don't hide it"),
    ...injections(text)
      .map((selector) => `${where} injects text with content: in ${selector}`),
  ]);
}

/** Each href selector in the web skin that names neither a socials URL
 *  nor one of the repo's own links. */
function hrefProblems(settings, payload, web) {
  const urls = [
    ...(payload.socials ?? []).map((s) => s.url),
    ...settings.ownLinks,
  ];
  return orphanHrefs(web, urls)
    .map((selector) => `${selector} in the web skin matches no socials URL`);
}

/** Each link class the repo names with no `a.<class>` rule in the email
 *  skin. */
function linkClassProblems(settings, email) {
  const emailRules = stripComments(email);
  return settings.linkClasses
    .filter((name) => !new RegExp(`a\\.${name}(?![\\w-])`).test(emailRules))
    .map((name) => `email class "${name}" has no a.${name} rule, so `
      + "the template's link colour would override it");
}

/** A hex colour in its long lower-case form, so `#ABC` and `#aabbcc`
 *  compare equal. */
function longHex(hex) {
  const h = hex.slice(1).toLowerCase();
  return h.length <= SHORT_HEX ? `#${[...h].map((c) => c + c).join("")}` : `#${h}`;
}

/** Each rule as [selector, body], selectors whitespace-normalised. A rule
 *  inside an at-rule takes the text after the at-rule's own brace. */
function rules(text) {
  return stripComments(text).split("}").flatMap((chunk) => {
    const brace = chunk.lastIndexOf("{");
    if (brace === -1) return [];
    const head = chunk.slice(0, brace);
    const selector = head.slice(head.lastIndexOf("{") + 1)
      .split(/\s+/).join(" ").trim();
    return [[selector, chunk.slice(brace + 1)]];
  });
}

/** Each declaration in a stylesheet as [property, value]. */
function declarations(text) {
  return rules(text).flatMap(([, body]) => body.split(";").flatMap((decl) => {
    const at = decl.indexOf(":");
    return at === -1
      ? []
      : [[decl.slice(0, at).trim(), decl.slice(at + 1).trim()]];
  }));
}

/** Declaration values only, so a selector such as `a:not(#cafe)` is not
 *  read as a colour. */
function cssValues(text) {
  return declarations(text).map(([, value]) => value).join(" ");
}

/** An SVG's attribute values. */
function attributeValues(text) {
  return [...text.matchAll(/="([^"]*)"/g)].map((m) => m[1]).join(" ");
}

/** Each hex colour in `values` the palette does not hold, once. */
function offPalette(values, palette) {
  return [...new Set(
    [...values.matchAll(/#[0-9a-f]{3,8}\b/gi)]
      .map((m) => m[0])
      .filter((hex) => !palette.has(longHex(hex))),
  )];
}

/** Each selector whose rule hides it: `display: none` or `font-size: 0`,
 *  important or not. */
function hides(text) {
  return rules(text)
    .filter(([, body]) => body.split(";").some((decl) =>
      /^(display:none|font-size:0)(!important)?$/.test(
        decl.replace(/\s/g, ""),
      )))
    .map(([selector]) => selector);
}

/** Each selector whose rule adds text with `content:`; a value that
 *  removes text is not an injection. */
function injections(text) {
  return rules(text)
    .filter(([selector, body]) => !selector.startsWith("@")
      && body.split(";").some((decl) => {
        // The whole property name: justify-, align- and place-content end
        // in content too.
        const at = decl.indexOf(":");
        if (at === -1 || decl.slice(0, at).trim() !== "content") return false;
        const value = decl.slice(at + 1).trim();
        const bare = value.endsWith(IMPORTANT)
          ? value.slice(0, -IMPORTANT.length).trim() : value;
        return !NO_CONTENT.has(bare);
      }))
    .map(([selector]) => selector);
}

/** A selector value without the quotes around it, if it has them. */
function unquote(value) {
  const quoted = value.length > 1 && /^["']/.test(value)
    && value.endsWith(value[0]);
  return quoted ? value.slice(1, -1) : value;
}

/** Every href attribute selector the skin keys on that names no socials
 *  URL, quoted either way or unquoted. */
function orphanHrefs(text, urls) {
  const matches = {
    "=": (url, v) => url === v,
    "~=": (url, v) => url.split(/\s+/).includes(v),
    "|=": (url, v) => url === v || url.startsWith(`${v}-`),
    "*=": (url, v) => url.includes(v),
    "^=": (url, v) => url.startsWith(v),
    "$=": (url, v) => url.endsWith(v),
  };
  return [...stripComments(text).matchAll(
    /\[\s*href\s*([~|*^$]?=)\s*("[^"]*"|'[^']*'|[^\s\]]+)(\s[^\]]*)?\]/gi,
  )]
    .filter(([, op, value, flag = ""]) => HREF_FLAG.test(flag)
      && !urls.some((url) => matches[op](url, unquote(value))))
    .map(([whole]) => whole);
}
